  -- Barrel aimed at the grid = a cylinder receding into the screen, which in
  -- one-point perspective is a cone whose apex is the VP. Coil spacing and
  -- radius shrink with depth on their own.
  local ax, ay, rA, fEnd = 556, 281, 13, 0.72
  local LA = sqrt((ax - VPX) ^ 2 + (ay - VPY) ^ 2)
  local hx, hy = (ax - VPX) / LA, (ay - VPY) / LA      -- axis, pointing away from the VP
  local nx, ny = hy, -hx                               -- up-right: the lit side
  local function sample(x, y)
    local qx, qy = x - VPX, y - VPY
    local f = (qx * hx + qy * hy) / LA                   -- 1 at the breech, fEnd at the muzzle
    local t = qx * nx + qy * ny
    local u = (1 / f - 1) / (1 / fEnd - 1)               -- 0..1 in true depth
    return f, t, u
  end
  ray(ax + nx * rA, ay + ny * rA, VPX + (ax + nx * rA - VPX) * fEnd, VPY + (ay + ny * rA - VPY) * fEnd)
  ray(ax - nx * rA, ay - ny * rA, VPX + (ax - nx * rA - VPX) * fEnd, VPY + (ay - ny * rA - VPY) * fEnd)
  local function coilAt(u) return u > 0.1 and u < 0.9 and (u * 7) % 1 < 0.42 end

  local barrel = {}
  for y = 200, H - 1 do for x = 430, W - 1 do
    local f, t, u = sample(x, y)
    if f >= fEnd and f <= 1 and abs(t) <= rA * f * (coilAt(u) and 1.16 or 1) then barrel[K(x, y)] = true end
