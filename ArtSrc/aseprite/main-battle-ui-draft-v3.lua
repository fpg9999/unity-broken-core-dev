-- masks (set of y*W+x, clipped to canvas) -------------------------------------
local function K(x, y) return y * W + x end
local function inb(x, y) return x >= 0 and y >= 0 and x < W and y < H end
local function mhas(m, x, y)
  if not inb(x, y) then return true end   -- shapes continue past the screen edge
  return m[K(x, y)] == true
end
local function poly(pts, m)
  m = m or {}
  local n = #pts
  local y0, y1 = math.huge, -math.huge
  for i = 1, n do y0 = min(y0, pts[i][2]); y1 = max(y1, pts[i][2]) end
  for y = max(0, ceil(y0)), min(H - 1, floor(y1)) do
    local xl, xr = math.huge, -math.huge
    for i = 1, n do
      local a, b = pts[i], pts[i % n + 1]
      local ay, by = a[2], b[2]
      if y >= min(ay, by) and y <= max(ay, by) then
        if ay == by then
          xl = min(xl, a[1], b[1]); xr = max(xr, a[1], b[1])
        else
          local x = a[1] + (b[1] - a[1]) * (y - ay) / (by - ay)
          xl = min(xl, x); xr = max(xr, x)
        end
      end
    end
    if xl <= xr then
      for x = max(0, ceil(xl - 1e-6)), min(W - 1, floor(xr + 1e-6)) do m[K(x, y)] = true end
    end
  end
  return m
end
local function mrect(x, y, w, h, m)
  m = m or {}
  for yy = y, y + h - 1 do for xx = x, x + w - 1 do if inb(xx, yy) then m[K(xx, yy)] = true end end end
  return m
end
local function mellipse(cx, cy, rx, ry, m)
  m = m or {}
  for y = floor(cy - ry), ceil(cy + ry) do
    for x = floor(cx - rx), ceil(cx + rx) do
      local u, v = (x - cx) / rx, (y - cy) / ry
      if u * u + v * v <= 1.0 and inb(x, y) then m[K(x, y)] = true end
    end
  end
  return m
end
local function munion(a, b) for k in pairs(b) do a[k] = true end return a end
local function msub(a, b) local r = {} for k in pairs(a) do if not b[k] then r[k] = true end end return r end
local function mshift(m, dx, dy)
  local r = {}
  for k in pairs(m) do
    local x, y = k % W + dx, k // W + dy
    if inb(x, y) then r[K(x, y)] = true end
  end
  return r
end
local function erode(m)
  local r = {}
  for k in pairs(m) do
    local x, y = k % W, k // W
    if mhas(m, x - 1, y) and mhas(m, x + 1, y) and mhas(m, x, y - 1) and mhas(m, x, y + 1) then r[k] = true end
  end
  return r
end
local function mpaint(m, c) for k in pairs(m) do put(k % W, k // W, c) end end
local function mpaintFn(m, fn)
  for k in pairs(m) do
    local x, y = k % W, k // W
    local c = fn(x, y)
    if c then put(x, y, c) end
  end
end
local function outline(m, c)
  for k in pairs(m) do
    local x, y = k % W, k // W
    if inb(x - 1, y) and not m[K(x - 1, y)] then put(x - 1, y, c) end
    if inb(x + 1, y) and not m[K(x + 1, y)] then put(x + 1, y, c) end
    if inb(x, y - 1) and not m[K(x, y - 1)] then put(x, y - 1, c) end
    if inb(x, y + 1) and not m[K(x, y + 1)] then put(x, y + 1, c) end
  end
end
-- 1px bevel ring: lit top/left, dark bottom/right (light comes from the top-left)
local function rims(m, top, left, right, bottom)
  for k in pairs(m) do
    local x, y = k % W, k // W
    if top and not mhas(m, x, y - 1) then put(x, y, top)
    elseif left and not mhas(m, x - 1, y) then put(x, y, left)
    elseif bottom and not mhas(m, x, y + 1) then put(x, y, bottom)
    elseif right and not mhas(m, x + 1, y) then put(x, y, right) end
  end
end
local function castShadow(m, dx, dy)
  for k in pairs(mshift(m, dx, dy)) do
    local x, y = k % W, k // W
    if not m[k] and pc.rgbaA(get(x, y)) == 0 then put(x, y, SH) end
  end
end

-- THE vanishing point. Hard-coded: dead centre of the 576x324 screen. Every
-- module derives its receding geometry from these two numbers only.
local VPX, VPY = 288, 162
local function toVP(x, y, s) return VPX + (x - VPX) * s, VPY + (y - VPY) * s end
local function R(v) return floor(v + 0.5) end
-- every receding edge drawn is logged here; `--script-param vpcheck=out.png`
-- exports an overlay extending each one so stray vanishing points stand out
local RAYS = {}
local function ray(x0, y0, x1, y1) RAYS[#RAYS + 1] = { x0, y0, x1, y1 } end

-- frontal rectangle with 45° chamfers (front faces sit on the picture plane)
local function crect(x0, y0, x1, y1, ch)
  return {
    { x0 + ch, y0 }, { x1 - ch, y0 }, { x1, y0 + ch }, { x1, y1 - ch },
    { x1 - ch, y1 }, { x0 + ch, y1 }, { x0, y1 - ch }, { x0, y0 + ch },
  }
end

local function lineIn(m, x0, y0, x1, y1, c)
  local dx, dy = abs(x1 - x0), -abs(y1 - y0)
  local sx, sy = x0 < x1 and 1 or -1, y0 < y1 and 1 or -1
  local err = dx + dy
  while true do
    if inb(x0, y0) and m[K(x0, y0)] then put(x0, y0, c) end
    if x0 == x1 and y0 == y1 then break end
    local e2 = 2 * err
    if e2 >= dy then err = err + dy; x0 = x0 + sx end
    if e2 <= dx then err = err + dx; y0 = y0 + sy end
  end
end

-- Box whose front face is on the picture plane and whose back face is the front
-- scaled toward the VP by o.s (1 = paper thin, smaller = deeper). A side face is
-- drawn only if it looks toward the VP, so left-of-centre boxes show their right
-- side, boxes above the VP show their underside, and so on - automatically.
local function shell(o)
  local face, s = o.face, o.s
  local F = poly(face)
  local S = munion({}, F)
  local n = #face
  local area = 0
  for i = 1, n do
    local a, b = face[i], face[i % n + 1]
    area = area + a[1] * b[2] - b[1] * a[2]
  end
  local sides = {}
  for i = 1, n do
    local a, b = face[i], face[i % n + 1]
    local ex, ey = b[1] - a[1], b[2] - a[2]
    local nx, ny
    if area > 0 then nx, ny = ey, -ex else nx, ny = -ey, ex end
    local mx, my = (a[1] + b[1]) / 2, (a[2] + b[2]) / 2
    if nx * (VPX - mx) + ny * (VPY - my) > 0 then
      local ax2, ay2 = toVP(a[1], a[2], s)
      local bx2, by2 = toVP(b[1], b[2], s)
      local q = poly({ a, b, { bx2, by2 }, { ax2, ay2 } })
      ray(a[1], a[2], ax2, ay2); ray(b[1], b[2], bx2, by2)
      local horiz = abs(nx) > abs(ny)
      local col
      if horiz then col = nx > 0 and (o.right or P1) or (o.left or P3)
      else col = ny < 0 and (o.top or P4) or (o.bottom or P0) end
      sides[#sides + 1] = { m = msub(q, F), c = col, a = a, b = b, horiz = horiz }
      munion(S, q)
    end
  end
  if o.shadow ~= false then castShadow(S, o.sx or 4, o.sy or 5) end
  for _, sd in ipairs(sides) do
    mpaint(sd.m, sd.c)
    -- ribs are rays from the front edge to the VP: they make the convergence legible
    if o.ribs ~= false then
      local len = max(abs(sd.b[1] - sd.a[1]), abs(sd.b[2] - sd.a[2]))
      local step = sd.horiz and 7 or 10
      for t = step, len - 3, step do
        local px = R(sd.a[1] + (sd.b[1] - sd.a[1]) * t / len)
        local py = R(sd.a[2] + (sd.b[2] - sd.a[2]) * t / len)
        local qx, qy = toVP(px, py, s)
        lineIn(sd.m, px, py, R(qx), R(qy), sd.horiz and (o.ribDark or P0) or (o.ribLight or P2))
      end
    end
  end
  mpaint(F, o.fill or P2)
  rims(F, o.rimT or S4, o.rimL or S3, o.rimR or S1, o.rimB or S1)
  if o.groove then rims(erode(erode(erode(F))), P1, P1, P3, P3) end
  outline(S, INK)
  return F, S
end

