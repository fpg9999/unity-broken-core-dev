local function wallPipe(xEdge, y1, y2, ramp)
  local xb = xEdge == 0 and bx0 or bx1
  local k = (xb - VPX) / (xEdge - VPX)
  local m = poly({ { xEdge, y1 }, { xEdge, y2 }, { xb, VPY + (y2 - VPY) * k }, { xb, VPY + (y1 - VPY) * k } })
  ray(xEdge, y1, xb, VPY + (y1 - VPY) * k)
  mpaintFn(m, function(x, y)
    local kk = (x - VPX) / (xEdge - VPX)
    local top, bot = VPY + (y1 - VPY) * kk, VPY + (y2 - VPY) * kk
    local v = (y - top) / max(1, bot - top)
    return ramp[min(#ramp, 1 + floor(v * #ramp))]
  end)
end
