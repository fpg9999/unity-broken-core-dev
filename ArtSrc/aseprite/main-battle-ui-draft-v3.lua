local function piece(cells, kind)
  local set = {}
  for _, cr in ipairs(cells) do set[cr[1] .. "," .. cr[2]] = true end
  local m = {}
  for _, cr in ipairs(cells) do
    local x, y = cellXY(cr[1], cr[2])
    mrect(x, y, 24, 24, m)
    if set[(cr[1] + 1) .. "," .. cr[2]] then mrect(x + 24, y, 1, 24, m) end
    if set[cr[1] .. "," .. (cr[2] + 1)] then mrect(x, y + 24, 24, 1, m) end
    if set[(cr[1] + 1) .. "," .. cr[2]] and set[cr[1] .. "," .. (cr[2] + 1)] and set[(cr[1] + 1) .. "," .. (cr[2] + 1)] then
      mrect(x + 24, y + 24, 1, 1, m)
    end
  end
  local core = erode(m)
  for k in pairs(msub(mshift(m, 2, 2), m)) do
    local x, y = k % W, k // W
    if x >= GX and x <= GX1 and y >= GY and y <= GY1 then put(x, y, SC0) end
  end
  local pal = ({
    bag    = { B0, B1, B2, B3 },
    barrel = { U0, U1, U2, U3 },
    scrap  = { S0, S1, S2, S3, S4 },
    crate  = { P1, P2, P3, P4 },
  })[kind]
  mpaint(core, pal[3])
  local inner = erode(core)
  rims(core, pal[4], pal[4], pal[2], pal[2])
  rims(msub(inner, erode(inner)), nil, nil, pal[2], pal[2])
  mpaint(msub(m, core), INK)
  for _, cr in ipairs(cells) do
    local x, y = cellXY(cr[1], cr[2])
    if kind == "bag" then
      line(x + 5, y + 8, x + 9, y + 12, B1); line(x + 15, y + 6, x + 18, y + 9, B1)
      line(x + 7, y + 17, x + 12, y + 19, B1); put(x + 6, y + 5, B3); put(x + 7, y + 5, B3); put(x + 6, y + 6, B3)
    elseif kind == "barrel" then
      for _, yy in ipairs({ 6, 17 }) do hline(x + 2, x + 21, y + yy, U1); hline(x + 2, x + 21, y + yy - 1, U3) end
      put(x + 15, y + 10, U0); put(x + 16, y + 10, U0); put(x + 16, y + 11, U0); put(x + 6, y + 20, U0)
      vline(x + 5, y + 2, y + 21, U3)
    elseif kind == "scrap" then
      line(x + 4, y + 18, x + 12, y + 6, S1); line(x + 13, y + 18, x + 19, y + 9, S1)
      put(x + 3, y + 3, S4); put(x + 20, y + 3, S4); put(x + 3, y + 20, S1); put(x + 20, y + 20, S1)
    elseif kind == "crate" then
      for _, yy in ipairs({ 8, 15 }) do hline(x + 2, x + 21, y + yy, P1); hline(x + 2, x + 21, y + yy + 1, P4) end
      put(x + 4, y + 4, S3); put(x + 19, y + 4, S3); put(x + 4, y + 19, S2); put(x + 19, y + 19, S2)
    end
  end
  -- knot on top of bags
  if kind == "bag" then
    local x, y = cellXY(cells[1][1], cells[1][2])
    rows(x + 9, y + 1, { ".#..#.", "##..##", ".####.", "..##.." }, { ["#"] = B3 })
  end
  return m
end
