-- masks (set of y*W+x, clipped to canvas) -------------------------------------
local function K(x, y) return y * W + x end
local function inb(x, y) return x >= 0 and y >= 0 and x < W and y < H end
local function mhas(m, x, y)
  if not inb(x, y) then return true end   -- shapes continue past the screen edge
  return m[K(x, y)] == true
end
local function poly(pts, m)
  m = m or {}
  local n = #pts
  local y0, y1 = math.huge, -math.huge
  for i = 1, n do y0 = min(y0, pts[i][2]); y1 = max(y1, pts[i][2]) end
  for y = max(0, ceil(y0)), min(H - 1, floor(y1)) do
    local xl, xr = math.huge, -math.huge
    for i = 1, n do
      local a, b = pts[i], pts[i % n + 1]
      local ay, by = a[2], b[2]
      if y >= min(ay, by) and y <= max(ay, by) then
        if ay == by then
          xl = min(xl, a[1], b[1]); xr = max(xr, a[1], b[1])
        else
          local x = a[1] + (b[1] - a[1]) * (y - ay) / (by - ay)
          xl = min(xl, x); xr = max(xr, x)
        end
      end
    end
    if xl <= xr then
      for x = max(0, ceil(xl - 1e-6)), min(W - 1, floor(xr + 1e-6)) do m[K(x, y)] = true end
    end
  end
  return m
end
local function mrect(x, y, w, h, m)
  m = m or {}
  for yy = y, y + h - 1 do for xx = x, x + w - 1 do if inb(xx, yy) then m[K(xx, yy)] = true end end end
  return m
end
local function mellipse(cx, cy, rx, ry, m)
  m = m or {}
  for y = floor(cy - ry), ceil(cy + ry) do
    for x = floor(cx - rx), ceil(cx + rx) do
      local u, v = (x - cx) / rx, (y - cy) / ry
      if u * u + v * v <= 1.0 and inb(x, y) then m[K(x, y)] = true end
    end
  end
  return m
end
local function munion(a, b) for k in pairs(b) do a[k] = true end return a end
local function msub(a, b) local r = {} for k in pairs(a) do if not b[k] then r[k] = true end end return r end
local function mshift(m, dx, dy)
  local r = {}
  for k in pairs(m) do
    local x, y = k % W + dx, k // W + dy
    if inb(x, y) then r[K(x, y)] = true end
  end
  return r
end
local function erode(m)
  local r = {}
  for k in pairs(m) do
    local x, y = k % W, k // W
    if mhas(m, x - 1, y) and mhas(m, x + 1, y) and mhas(m, x, y - 1) and mhas(m, x, y + 1) then r[k] = true end
  end
  return r
end
local function mpaint(m, c) for k in pairs(m) do put(k % W, k // W, c) end end
local function mpaintFn(m, fn)
  for k in pairs(m) do
    local x, y = k % W, k // W
    local c = fn(x, y)
    if c then put(x, y, c) end
  end
end
local function outline(m, c)
  for k in pairs(m) do
    local x, y = k % W, k // W
    if inb(x - 1, y) and not m[K(x - 1, y)] then put(x - 1, y, c) end
    if inb(x + 1, y) and not m[K(x + 1, y)] then put(x + 1, y, c) end
    if inb(x, y - 1) and not m[K(x, y - 1)] then put(x, y - 1, c) end
    if inb(x, y + 1) and not m[K(x, y + 1)] then put(x, y + 1, c) end
  end
end
-- 1px bevel ring: lit top/left, dark bottom/right (light comes from the top-left)
local function rims(m, top, left, right, bottom)
  for k in pairs(m) do
    local x, y = k % W, k // W
    if top and not mhas(m, x, y - 1) then put(x, y, top)
    elseif left and not mhas(m, x - 1, y) then put(x, y, left)
    elseif bottom and not mhas(m, x, y + 1) then put(x, y, bottom)
    elseif right and not mhas(m, x + 1, y) then put(x, y, right) end
  end
end
local function castShadow(m, dx, dy)
  for k in pairs(mshift(m, dx, dy)) do
    local x, y = k % W, k // W
    if not m[k] and pc.rgbaA(get(x, y)) == 0 then put(x, y, SH) end
  end
end

-- chamfered quad: left/right x, top y at left/right, bottom y at left/right
local function cquad(x0, x1, t0, t1, b0, b1, ch)
  return {
    { x0 + ch, t0 }, { x1 - ch, t1 }, { x1, t1 + ch }, { x1, b1 - ch },
    { x1 - ch, b1 }, { x0 + ch, b0 }, { x0, b0 - ch }, { x0, t0 + ch },
  }
end

-- Extruded shell. o.face convex pts, o.d depth vector toward the vanishing point.
local function shell(o)
  local face, d = o.face, o.d
  local F = poly(face)
  local S = munion({}, F)
  local sides = {}
  local n = #face
  local area = 0
  for i = 1, n do
    local a, b = face[i], face[i % n + 1]
    area = area + a[1] * b[2] - b[1] * a[2]
  end
  for i = 1, n do
    local a, b = face[i], face[i % n + 1]
    local ex, ey = b[1] - a[1], b[2] - a[2]
    local nx, ny
    if area > 0 then nx, ny = ey, -ex else nx, ny = -ey, ex end
    if nx * d[1] + ny * d[2] > 0 then
      local q = poly({ a, b, { b[1] + d[1], b[2] + d[2] }, { a[1] + d[1], a[2] + d[2] } })
      local col
      if abs(nx) > abs(ny) then col = nx > 0 and (o.right or P1) or (o.left or P1)
      else col = ny < 0 and (o.top or P3) or (o.bottom or P0) end
      sides[#sides + 1] = { msub(q, F), col, nx, ny }
      munion(S, q)
    end
  end
  if o.shadow ~= false then castShadow(S, o.sx or 4, o.sy or 5) end
  for _, s in ipairs(sides) do
    mpaint(s[1], s[2])
    -- ribs running along the depth direction sell the slab thickness
    if o.ribs ~= false and d[1] ~= 0 and d[2] ~= 0 then
      local horiz = abs(s[3]) > abs(s[4])
      for k in pairs(s[1]) do
        local x, y = k % W, k // W
        if horiz then
          if floor(y - x * d[2] / d[1]) % 7 == 0 then put(x, y, o.ribDark or P0) end
        else
          if floor(x - y * d[1] / d[2]) % 9 == 0 then put(x, y, o.ribLight or P2) end
        end
      end
    end
  end
  mpaint(F, o.fill or P2)
  rims(F, o.rimT or S4, o.rimL or S3, o.rimR or S1, o.rimB or S1)
  if o.groove then
    local e = erode(erode(erode(F)))
    rims(e, P1, P1, P3, P3)
  end
  outline(S, INK)
  return F, S
end

