  for _, cr in ipairs(cells) do set[cr[1] .. "," .. cr[2]] = true end
  local m = {}
  for _, cr in ipairs(cells) do
    local x, y = cellXY(cr[1], cr[2])
    mrect(x, y, 24, 24, m)
    if set[(cr[1] + 1) .. "," .. cr[2]] then mrect(x + 24, y, 1, 24, m) end
    if set[cr[1] .. "," .. (cr[2] + 1)] then mrect(x, y + 24, 24, 1, m) end
    if set[(cr[1] + 1) .. "," .. cr[2]] and set[cr[1] .. "," .. (cr[2] + 1)] and set[(cr[1] + 1) .. "," .. (cr[2] + 1)] then
      mrect(x + 24, y + 24, 1, 1, m)
    end
  end
