-- CJK text --------------------------------------------------------------------
local function tw(s, size)
  local f = GLYPHS[size or 12]
  local w = 0
  for _, cp in utf8.codes(s) do
    if cp == 32 then w = w + (size or 12) // 3
    else local g = f[cp]; w = w + (g and g.w or size or 12) end
  end
  return w
end
local function txt(s, x, y, c, size, shadow, shearK)
  size = size or 12
  local f = GLYPHS[size]
  local x0 = x
  local function pass(col, ox, oy)
    local cx = x0
    for _, cp in utf8.codes(s) do
      if cp == 32 then cx = cx + size // 3
      else
        local g = f[cp]
        if g then
          for j = 1, #g do
            local row = g[j]
            for i = 1, #row do
              if row:sub(i, i) == "#" then
                local px = cx + i - 1
                local py = y + j - 1
                if shearK then py = py - floor((px - x0) / shearK) end
                put(px + ox, py + oy, col)
              end
            end
          end
          cx = cx + g.w
        else
          cx = cx + size
        end
      end
    end
  end
  local saved = cur
  cur = txtImg
  if shadow then pass(shadow, 1, 1) end
  pass(c, 0, 0)
  cur = saved
end
local function txtC(s, cx, y, c, size, shadow) txt(s, cx - tw(s, size) // 2, y, c, size, shadow) end

