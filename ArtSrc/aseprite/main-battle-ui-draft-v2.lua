  local nx, ny = -uy, ux          -- points up-right: the lit side
  local function coilAt(s) return s > 18 and s < L - 14 and (floor(s) % 11) < 5 end
  local function radiusAt(s) return coilAt(s) and r + 2 or r end


  local barrel = {}
  for y = 200, H - 1 do for x = 420, W - 1 do
    local px, py = x - ax, y - ay
    local s, tt = px * ux + py * uy, px * nx + py * ny
    if s >= 0 and s <= L + 1 and abs(tt) <= radiusAt(s) then
      barrel[K(x, y)] = true
    end
  end end
  castShadow(barrel, 4, 6)
  mpaintFn(barrel, function(x, y)
    local px, py = x - ax, y - ay
    local s = px * ux + py * uy
    local t = (px * nx + py * ny) / radiusAt(s)
    if coilAt(s) then
      local m = floor(s) % 11
      if m == 0 or m == 4 then return U0 end
      if t > 0.5 then return U3 elseif t > -0.15 then return U2 elseif t > -0.65 then return U1 else return U0 end
    end
    if t > 0.82 then return S2 elseif t > 0.45 then return S4 elseif t > 0.05 then return S3
