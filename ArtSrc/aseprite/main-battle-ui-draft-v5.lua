-- digits; `slope` shears them so the baseline follows a ray (per scaled pixel)
local function num(s, x, y, c, sc, shadow, slope)
  sc = sc or 1
  slope = slope or 0
  local x0 = x
  local saved = cur
  cur = txtImg
  for pass = 1, 2 do
    local col, o = pass == 1 and shadow or c, pass == 1 and 1 or 0
    if col then
      local cx = x0
      for i = 1, #s do
        local g = DIG[s:sub(i, i)]
        if g then
          for j, row in ipairs(g) do
            for k = 1, 5 do
              if row:sub(k, k) == "#" then
                local bx = cx + (k - 1) * sc
                local off = sc * R((bx - x0) * slope / sc)
                for a = 0, sc - 1 do for b = 0, sc - 1 do
                  put(bx + a + o, y + (j - 1) * sc + b + off + o, col)
                end end
              end
            end
          end
        end
        cx = cx + 6 * sc
      end
    end
  end
  cur = saved
end

-- CJK text --------------------------------------------------------------------
local function tw(s, size)
  local f = GLYPHS[size or 12]
  local w = 0
  for _, cp in utf8.codes(s) do
    if cp == 32 then w = w + (size or 12) // 3
    else local g = f[cp]; w = w + (g and g.w or size or 12) end
  end
  return w
end
local function txt(s, x, y, c, size, shadow, slope)
  size = size or 12
  slope = slope or 0
  local f = GLYPHS[size]
  local x0 = x
  local function pass(col, ox, oy)
    local cx = x0
    for _, cp in utf8.codes(s) do
      if cp == 32 then cx = cx + size // 3
      else
        local g = f[cp]
        if g then
          for j = 1, #g do
            local row = g[j]
            for i = 1, #row do
              if row:sub(i, i) == "#" then
                local px = cx + i - 1
                put(px + ox, y + j - 1 + R((px - x0) * slope) + oy, col)
              end
            end
          end
          cx = cx + g.w
        else
          cx = cx + size
        end
      end
    end
  end
  local saved = cur
  cur = txtImg
  -- sheared text drops its shadow straight down so the slant stays clean
  if shadow then pass(shadow, abs(slope) > 0.2 and 0 or 1, 1) end
  pass(c, 0, 0)
  cur = saved
end
local function txtC(s, cx, y, c, size, shadow) txt(s, cx - tw(s, size) // 2, y, c, size, shadow) end

-- text / digits written on a wall face: centred on face line `a`, starting at
-- screen column x (align "c" centres on x), baseline sheared along the ray
local function ftxt(f, s, x, a, c, size, shadow, align)
  size = size or 12
  local wd = tw(s, size)
  if align == "c" then x = x - wd // 2 elseif align == "r" then x = x - wd end
  local yc = fy(f, x, a)
  txt(s, x, R(yc - GLYPHS[size].h / 2), c, size, shadow, slopeAt(x, yc))
end
-- vertical writing: on a wall face a vertical line keeps one depth, so a
-- column of glyphs needs no shear at all (used where the rays get steep)
local function vtxt(s, x, yc, c, size, shadow)
  size = size or 12
  local h = GLYPHS[size].h
  local n = utf8.len(s)
  local y = R(yc - (n * (h + 1) - 1) / 2)
  for _, cp in utf8.codes(s) do
    txt(utf8.char(cp), x, y, c, size, shadow)
    y = y + h + 1
  end
end
local function fnum(f, s, x, a, c, sc, shadow, align)
  sc = sc or 1
  local wd = numW(s, sc)
  if align == "c" then x = x - wd // 2 elseif align == "r" then x = x - wd end
  local yc = fy(f, x, a)
  num(s, x, R(yc - 7 * sc / 2), c, sc, shadow, slopeAt(x, yc))
end
local function frows(f, x, a, data, legend)
  local yc = fy(f, x, a)
  rows(x, R(yc - #data / 2), data, legend, slopeAt(x, yc))
end

