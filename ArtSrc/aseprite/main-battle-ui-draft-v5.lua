if app.params.vpcheck then
  local ov = spr:newLayer(); ov.name = "vp-check"
  local img = Image(W, H, ColorMode.RGB)
  cur = img
  local worst, worstEnd, used = 0, 0, 0
  local misses = {}
  for _, r in ipairs(RAYS) do
    if (r[3] - r[1]) * (VPX - r[1]) + (r[4] - r[2]) * (VPY - r[2]) < 0 then r = { r[3], r[4], r[1], r[2] } end
    local dx, dy = r[3] - r[1], r[4] - r[2]
    local len = sqrt(dx * dx + dy * dy)
    if len >= 1 then
      used = used + 1
      local miss = abs((VPX - r[1]) * dy - (VPY - r[2]) * dx) / len
      local L = sqrt((VPX - r[1]) ^ 2 + (VPY - r[2]) ^ 2)
      local endErr = miss * len / L
      worst = max(worst, miss); worstEnd = max(worstEnd, endErr)
      misses[#misses + 1] = { endErr, miss, r }
      for i = 0, floor(L) do
        if i % 4 < 2 then put(R(r[1] + dx / len * i), R(r[2] + dy / len * i), R3) end
      end
    end
  end
  for i = -8, 8 do put(VPX + i, VPY, C3); put(VPX, VPY + i, C3) end
  spr:newCel(ov, 1, img, Point(0, 0))
  spr:saveCopyAs(app.params.vpcheck)
  table.sort(misses, function(a, b) return a[1] > b[1] end)
  print(string.format("vp-check: %d receding edges toward VP (%d,%d); worst endpoint drift %.2f px, worst extended miss %.2f px",
    used, VPX, VPY, worstEnd, worst))
  for i = 1, min(4, #misses) do
    local m = misses[i]
    print(string.format("  drift %.2f px  miss %.2f px  edge (%.1f,%.1f)->(%.1f,%.1f)", m[1], m[2], m[3][1], m[3][2], m[3][3], m[3][4]))
  end
end
