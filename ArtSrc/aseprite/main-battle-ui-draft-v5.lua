local function hline(x1, x2, y, c) for x = min(x1, x2), max(x1, x2) do put(x, y, c) end end
local function vline(x, y1, y2, c) for y = min(y1, y2), max(y1, y2) do put(x, y, c) end end
local function line(x0, y0, x1, y1, c)
  x0, y0, x1, y1 = R(x0), R(y0), R(x1), R(y1)
  local dx, dy = abs(x1 - x0), -abs(y1 - y0)
  local sx, sy = x0 < x1 and 1 or -1, y0 < y1 and 1 or -1
  local err = dx + dy
  while true do
    put(x0, y0, c)
    if x0 == x1 and y0 == y1 then break end
    local e2 = 2 * err
    if e2 >= dy then err = err + dy; x0 = x0 + sx end
    if e2 <= dx then err = err + dx; y0 = y0 + sy end
  end
end
local function rows(x, y, data, legend, slope)
  for j, row in ipairs(data) do
    for i = 1, #row do
      local c = legend[row:sub(i, i)]
      if c then put(x + i - 1, y + j - 1 + (slope and R((i - 1) * slope) or 0), c) end
    end
  end
end

-- masks (set of y*W+x, clipped to canvas) -------------------------------------
local function K(x, y) return y * W + x end
local function inb(x, y) return x >= 0 and y >= 0 and x < W and y < H end
local function mhas(m, x, y)
  if not inb(x, y) then return true end   -- shapes continue past the screen edge
  return m[K(x, y)] == true
end
local function poly(pts, m)
  m = m or {}
  local n = #pts
  local y0, y1 = math.huge, -math.huge
  for i = 1, n do y0 = min(y0, pts[i][2]); y1 = max(y1, pts[i][2]) end
  for y = max(0, ceil(y0 - 1e-6)), min(H - 1, floor(y1 + 1e-6)) do
    local xl, xr = math.huge, -math.huge
    for i = 1, n do
      local a, b = pts[i], pts[i % n + 1]
      local ay, by = a[2], b[2]
      if y >= min(ay, by) - 1e-6 and y <= max(ay, by) + 1e-6 then
        if abs(ay - by) < 1e-9 then
          xl = min(xl, a[1], b[1]); xr = max(xr, a[1], b[1])
        else
          local x = a[1] + (b[1] - a[1]) * (y - ay) / (by - ay)
          xl = min(xl, x); xr = max(xr, x)
        end
      end
    end
    if xl <= xr then
      for x = max(0, ceil(xl - 1e-6)), min(W - 1, floor(xr + 1e-6)) do m[K(x, y)] = true end
    end
  end
  return m
end
local function mrect(x, y, w, h, m)
  m = m or {}
  for yy = y, y + h - 1 do for xx = x, x + w - 1 do if inb(xx, yy) then m[K(xx, yy)] = true end end end
  return m
end
local function mellipse(cx, cy, rx, ry, m)
  m = m or {}
  for y = floor(cy - ry), ceil(cy + ry) do
    for x = floor(cx - rx), ceil(cx + rx) do
      local u, v = (x - cx) / rx, (y - cy) / ry
      if u * u + v * v <= 1.0 and inb(x, y) then m[K(x, y)] = true end
    end
  end
  return m
end
local function munion(a, b) for k in pairs(b) do a[k] = true end return a end
local function msub(a, b) local r = {} for k in pairs(a) do if not b[k] then r[k] = true end end return r end
local function mshift(m, dx, dy)
  local r = {}
  for k in pairs(m) do
    local x, y = k % W + dx, k // W + dy
    if inb(x, y) then r[K(x, y)] = true end
  end
  return r
end
local function erode(m)
  local r = {}
  for k in pairs(m) do
    local x, y = k % W, k // W
    if mhas(m, x - 1, y) and mhas(m, x + 1, y) and mhas(m, x, y - 1) and mhas(m, x, y + 1) then r[k] = true end
  end
  return r
end
local function mpaint(m, c) for k in pairs(m) do put(k % W, k // W, c) end end
local function mpaintFn(m, fn)
  for k in pairs(m) do
    local x, y = k % W, k // W
    local c = fn(x, y)
    if c then put(x, y, c) end
  end
end
local function outline(m, c)
  for k in pairs(m) do
    local x, y = k % W, k // W
    if inb(x - 1, y) and not m[K(x - 1, y)] then put(x - 1, y, c) end
    if inb(x + 1, y) and not m[K(x + 1, y)] then put(x + 1, y, c) end
    if inb(x, y - 1) and not m[K(x, y - 1)] then put(x, y - 1, c) end
    if inb(x, y + 1) and not m[K(x, y + 1)] then put(x, y + 1, c) end
  end
end
-- 1px bevel ring: lit top/left, dark bottom/right (light comes from the top-left)
local function rims(m, top, left, right, bottom)
  for k in pairs(m) do
    local x, y = k % W, k // W
    if top and not mhas(m, x, y - 1) then put(x, y, top)
    elseif left and not mhas(m, x - 1, y) then put(x, y, left)
    elseif bottom and not mhas(m, x, y + 1) then put(x, y, bottom)
    elseif right and not mhas(m, x + 1, y) then put(x, y, right) end
  end
end
local function castShadow(m, dx, dy)
  for k in pairs(mshift(m, dx, dy)) do
    local x, y = k % W, k // W
    if not m[k] and pc.rgbaA(get(x, y)) == 0 then put(x, y, SH) end
  end
end
local function lineIn(m, x0, y0, x1, y1, c)
  x0, y0, x1, y1 = R(x0), R(y0), R(x1), R(y1)
  local dx, dy = abs(x1 - x0), -abs(y1 - y0)
  local sx, sy = x0 < x1 and 1 or -1, y0 < y1 and 1 or -1
  local err = dx + dy
  while true do
    if inb(x0, y0) and m[K(x0, y0)] then put(x0, y0, c) end
    if x0 == x1 and y0 == y1 then break end
    local e2 = 2 * err
    if e2 >= dy then err = err + dy; x0 = x0 + sx end
    if e2 <= dx then err = err + dx; y0 = y0 + sy end
  end
end

--==============================================================================
-- THE vanishing point. Hard-coded: dead centre of the 576x324 screen. Every
-- face, edge, text baseline and warp below derives its depth from these two
-- numbers only.
--==============================================================================
local VPX, VPY = 288, 162
local function toVP(x, y, s) return VPX + (x - VPX) * s, VPY + (y - VPY) * s end
-- every receding edge drawn is logged; `--script-param vpcheck=out.png` exports
-- an overlay that extends each one, so a stray vanishing point would stand out
local RAYS = {}
local function ray(x0, y0, x1, y1) RAYS[#RAYS + 1] = { x0, y0, x1, y1 } end

-- Tilted faces ------------------------------------------------------------------
-- wallFace: a vertical plane that contains the view axis (a "side wall"). Its
--   near edge is the screen column xn from y=tn to y=bn; its far edge is the
--   column xf, where the face has shrunk toward the VP by kf. Left of the VP it
--   faces right, right of the VP it faces left.
-- flatFace: a horizontal plane (desk top below the VP, ceiling above it). Near
--   edge is the row yn from x=ln to x=rn, far edge the row yf.
-- Face coordinates: w = 0 near .. 1 far in true depth, a = 0..1 across.
local function wallFace(xn, tn, bn, xf)
  local kf = (xf - VPX) / (xn - VPX)
  return { kind = "wall", xn = xn, tn = tn, bn = bn, xf = xf, kf = kf, D = 1 / kf - 1, dir = xn < VPX and -1 or 1 }
end
local function flatFace(yn, ln, rn, yf)
  local kf = (yf - VPY) / (yn - VPY)
  return { kind = "flat", yn = yn, ln = ln, rn = rn, yf = yf, kf = kf, D = 1 / kf - 1, dir = yn < VPY and -1 or 1 }
end
local function fk(f, w) return 1 / (1 + w * f.D) end
local function fpt(f, w, a)
  local k = fk(f, w)
  if f.kind == "wall" then
    return VPX + (f.xn - VPX) * k, VPY + (f.tn + (f.bn - f.tn) * a - VPY) * k
  end
  return VPX + (f.ln + (f.rn - f.ln) * a - VPX) * k, VPY + (f.yn - VPY) * k
end
local function fquad(f, w0, w1, a0, a1)
  local p = {}
  for i, wa in ipairs({ { w0, a0 }, { w1, a0 }, { w1, a1 }, { w0, a1 } }) do
    local x, y = fpt(f, wa[1], wa[2]); p[i] = { x, y }
  end
  return p
end
local function finv(f, x, y)
  if f.kind == "wall" then
    local k = (x - VPX) / (f.xn - VPX)
    return (1 / k - 1) / f.D, ((y - VPY) / k + VPY - f.tn) / (f.bn - f.tn)
  end
  local k = (y - VPY) / (f.yn - VPY)
  return (1 / k - 1) / f.D, ((x - VPX) / k + VPX - f.ln) / (f.rn - f.ln)
end
local function wAtX(f, x) return ((f.xn - VPX) / (x - VPX) - 1) / f.D end
-- screen y of the face line `a` at screen column x (wall faces)
local function fy(f, x, a)
  local k = (x - VPX) / (f.xn - VPX)
  return VPY + (f.tn + (f.bn - f.tn) * a - VPY) * k
end
-- quad on a wall face between screen columns x0..x1 and face lines a0..a1;
-- its first and last edges are rays, like fquad
local function qx(f, x0, x1, a0, a1)
  return { { x0, fy(f, x0, a0) }, { x1, fy(f, x1, a0) }, { x1, fy(f, x1, a1) }, { x0, fy(f, x0, a1) } }
end
local function slopeAt(x, y) return (VPY - y) / (VPX - x) end
local function logQuad(p) ray(p[1][1], p[1][2], p[2][1], p[2][2]); ray(p[4][1], p[4][2], p[3][1], p[3][2]) end

-- Slab: a panel of thickness t whose big face is `f`. Besides the face we see
-- the frontal end at its near edge and, depending on where it sits relative to
-- the VP, its top or underside (walls) or one flank (desks).
local function slab(f, o)
  local t = o.t or 5
  local kf = f.kf
  local face = poly(fquad(f, 0, 1, 0, 1))
  local all = munion({}, face)
  local parts = {}
  local function add(pts, c, lit)
    local m = msub(poly(pts), face)
    parts[#parts + 1] = { m, c, lit }
    munion(all, m)
  end
  local function far(x, y) local px, py = toVP(x, y, kf); return { px, py } end
  local function rayTo(x, y) local p = far(x, y); ray(x, y, p[1], p[2]) end
  if f.kind == "wall" then
    local xo = f.xn + f.dir * t
    local xa, xb = min(xo, f.xn), max(xo, f.xn)
    add({ { xa, f.tn }, { xb, f.tn }, { xb, f.bn }, { xa, f.bn } }, o.endc, o.endLit)
    if f.tn > VPY then add({ { xo, f.tn }, { f.xn, f.tn }, far(f.xn, f.tn), far(xo, f.tn) }, o.topc); rayTo(xo, f.tn) end
    if f.bn < VPY then add({ { xo, f.bn }, { f.xn, f.bn }, far(f.xn, f.bn), far(xo, f.bn) }, o.botc or o.endc); rayTo(xo, f.bn) end
    rayTo(f.xn, f.tn); rayTo(f.xn, f.bn)
  else
    local yo = f.yn + f.dir * t
    local ya, yb = min(yo, f.yn), max(yo, f.yn)
    add({ { f.ln, ya }, { f.rn, ya }, { f.rn, yb }, { f.ln, yb } }, o.endc, o.endLit)
    if f.ln > VPX then add({ { f.ln, f.yn }, { f.ln, yo }, far(f.ln, yo), far(f.ln, f.yn) }, o.sidec or o.endc); rayTo(f.ln, yo) end
    if f.rn < VPX then add({ { f.rn, f.yn }, { f.rn, yo }, far(f.rn, yo), far(f.rn, f.yn) }, o.sidec or o.endc); rayTo(f.rn, yo) end
    rayTo(f.ln, f.yn); rayTo(f.rn, f.yn)
  end
  if o.shadow ~= false then castShadow(all, o.sx or 4, o.sy or 5) end
  for _, p in ipairs(parts) do
    mpaint(p[1], p[2])
    if p[3] then rims(p[1], p[3], nil, nil, nil) end
  end
  mpaint(face, o.fill)
  rims(face, o.rimT, o.rimL, o.rimR, o.rimB)
  outline(all, INK)
  -- rivets: two per panel, always on the frontal end, same rhythm everywhere
  if o.rivet and f.kind == "wall" then
    local xo = f.xn + f.dir * t
    local rx = R((xo + f.xn) / 2) - 1
    for _, y in ipairs({ f.tn + 3, f.bn - 5 }) do
      put(rx, y, o.rivet[1]); put(rx + 1, y, o.rivet[2]); put(rx, y + 1, o.rivet[2]); put(rx + 1, y + 1, INK)
    end
  end
  return face, all
end

