  -- Barrel aimed at the grid = a cylinder receding into the screen, which in
  -- one-point perspective is a cone whose apex is the VP.
  local ax, ay, rA, fEnd = 556, 258, 12, 0.74
  local LA = sqrt((ax - VPX) ^ 2 + (ay - VPY) ^ 2)
  local hx, hy = (ax - VPX) / LA, (ay - VPY) / LA
  local nx, ny = hy, -hx
  local function sample(x, y)
    local qx2, qy2 = x - VPX, y - VPY
    local f = (qx2 * hx + qy2 * hy) / LA
    local t = qx2 * nx + qy2 * ny
    local u = (1 / f - 1) / (1 / fEnd - 1)
    return f, t, u
  end
  ray(ax + nx * rA, ay + ny * rA, VPX + (ax + nx * rA - VPX) * fEnd, VPY + (ay + ny * rA - VPY) * fEnd)
  ray(ax - nx * rA, ay - ny * rA, VPX + (ax - nx * rA - VPX) * fEnd, VPY + (ay - ny * rA - VPY) * fEnd)
  local function coilAt(u) return u > 0.12 and u < 0.88 and (u * 6) % 1 < 0.42 end
  local barrel = {}
  for y = 200, H - 1 do for x = 440, W - 1 do
    local f, t, u = sample(x, y)
    if f >= fEnd and f <= 1 and abs(t) <= rA * f * (coilAt(u) and 1.16 or 1) then barrel[K(x, y)] = true end
  end end
  castShadow(barrel, 4, 6)
  mpaintFn(barrel, function(x, y)
    local f, t, u = sample(x, y)
    if coilAt(u) then
      local v = t / (rA * f * 1.16)
      local ph = (u * 6) % 1
      if ph < 0.06 or ph > 0.36 then return QU0 end
      if u > 0.62 then return v > 0.3 and QY3 or (v > -0.4 and QY2 or QY1) end
      if v > 0.5 then return QU3 elseif v > -0.15 then return QU2 elseif v > -0.65 then return QU1 else return QU0 end
    end
    local v = t / (rA * f)
    if v > 0.82 then return QS2 elseif v > 0.45 then return QS4 elseif v > 0.05 then return QS3
    elseif v > -0.4 then return QS2 elseif v > -0.78 then return QS1 else return QS0 end
  end)
  outline(barrel, INK)
  for _, side in ipairs({ -1, 1 }) do
    local m = {}
    for i = 0, 10 do
      local f = fEnd - i * 0.006
      local px, py = VPX + hx * LA * f, VPY + hy * LA * f
      local off = side * rA * f * 0.85
      mrect(R(px + nx * off) - 1, R(py + ny * off) - 1, 3, 3, m)
    end
    mpaint(m, side > 0 and QS3 or QS1)
    rims(m, side > 0 and QS4 or QS2, nil, nil, nil)
    outline(m, INK)
  end
  local ex, ey = R(VPX + hx * LA * (fEnd - 0.012)), R(VPY + hy * LA * (fEnd - 0.012))
  local emit = mellipse(ex, ey, 5, 5)
  mpaint(emit, QC1); mpaint(mellipse(ex - 1, ey - 1, 3, 3), QC2); mpaint(mellipse(ex - 2, ey - 2, 1, 1), QC3)
