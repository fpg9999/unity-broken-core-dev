    local v = t / (rA * 1.35)
    if f < 0.99 then return v > 0.3 and QS4 or (v > -0.5 and QS2 or QS0) end
    if v > 0.5 then return Q3 elseif v > -0.2 then return Q2 elseif v > -0.7 then return Q1 else return Q0 end
  end)
  outline(cap, INK)

end

