-- inverse-map a rectangle of the scratch image onto part of a face
local function warp(f, mask, w0, w1, a0, a1, sx, sy, sw, sh)
  for k in pairs(mask) do
    local x, y = k % W, k // W
    local w, a = finv(f, x, y)
    local u, v = (w - w0) / (w1 - w0), (a - a0) / (a1 - a0)
    local ix, iy
    if f.kind == "wall" then
      ix, iy = (f.dir > 0) and (1 - u) or u, v
    else
      ix, iy = v, (f.dir > 0) and (1 - u) or u
    end
    if ix >= 0 and ix < 1 and iy >= 0 and iy < 1 then
      local c = scr:getPixel(sx + floor(ix * sw), sy + floor(iy * sh))
      if pc.rgbaA(c) > 0 then put(x, y, c) end
    end
  end
end

local function hazard(x, y, w, h, a, b, period)
  period = period or 6
  for yy = y, y + h - 1 do
    for xx = x, x + w - 1 do
      put(xx, yy, ((xx + 2 * yy) // period) % 2 == 0 and a or b)
    end
  end
end
local function arrowTri(x, y, dir, c)
